<#
  seal_secrets.ps1 -- put plain-text secret files into ONE encrypted 7-Zip archive, then remove the
  plain copies (PC, D: and the NAS archive copy). 2026-11-13, Claude.

  Jason, 11-13: "clean up all access to plain text files". Found by tools/secret_scan.py.
  The archive password is generated by Proton Pass and lives only there:
     vault "Keys", item "Sealed secrets archive <date>" (login, field password).
  Open the archive later:  7z x -p<that password> D:\vault-sealed\sealed-secrets-<date>.7z -oSOMEWHERE
  The archive uses -mhe=on, so even the file NAMES inside are hidden without the password.

    powershell -File seal_secrets.ps1           dry run: lists what would be sealed and removed
    powershell -File seal_secrets.ps1 -Apply    seal, test the archive, copy it to the NAS (removes nothing)
    powershell -File seal_secrets.ps1 -Apply -Remove   same, then delete the plain copies (Jason runs this)

  Originals are removed only after `7z t` passes on the archive. That is a permanent delete on purpose:
  the Recycle Bin would keep a plain copy, which is what this is meant to end.
  Stale Claude worktrees go through `git worktree remove --force` so git forgets them too.

  -Day yyyy-MM-dd  reuse an existing archive and its Pass password instead of today's date.
     Added 2026-11-14: without it, a run on a later day built a NEW archive and a new Pass item, so
     the archive Jason had opened and checked was not the one the -Remove step relied on.
     Use:  powershell -File seal_secrets.ps1 -Apply -Remove -Day 2026-11-13
#>
param([switch]$Apply, [switch]$Remove, [string]$Day = (Get-Date -Format 'yyyy-MM-dd'))
$ErrorActionPreference = 'Continue'  # 'Stop' turns pass-cli's normal "No item" stderr into a crash on PS 5.1; failures are checked explicitly
$day = $Day
$out = 'D:\vault-sealed'
$arc = "$out\sealed-secrets-$day.7z"
$title = "Sealed secrets archive $day"
$sevenZ = 'C:\Program Files\7-Zip\7z.exe'
$nas = 'T:\Archive-2026-11-13'
$Targets = @(
  'D:\ai-stack-archive\env-backups',                                   # 10 old .env copies with live-era keys
  'D:\doc-gather\secrets-review',                                      # recovery codes, BitLocker, Wi-Fi
  'D:\secrets-ui-test',                                                # Chrome test profile (cookies)
  'C:\Jasons New Site\www\ai-stack\watchdog\secrets.env',              # replaced by pass:// in compose (11-13)
  'C:\Jasons New Site\www\ai-stack\All-Documents\Projects\PC-to-Linux-2026-10\secrets.txt',
  'D:\ai-stack-backup-2026-11-12\watchdog\secrets.env',
  'D:\ai-stack-backup-2026-11-12\logging\grafana-provisioning\alerting\contact-points.yaml',
  'D:\ai-stack-backup-2026-11-12\wazuh\wazuh-docker\single-node\config\wazuh_indexer_ssl_certs',
  'D:\ai-stack-backup-2026-11-12\wazuh-docker\single-node\config\wazuh_indexer_ssl_certs',
  'D:\ai-stack-archive\outdated\logging\grafana-provisioning\alerting\contact-points.yaml',
  'D:\ai-stack-archive\outdated\wazuh\wazuh-docker\single-node\config\wazuh_indexer_ssl_certs',
  'D:\ai-stack-archive\outdated\wazuh-docker\single-node\config\wazuh_indexer_ssl_certs',
  'C:\Jasons New Site\www\ai-stack\.claude\worktrees'                  # 5 stale agent sandboxes (Oct), copies of old secrets
) | Where-Object { Test-Path -LiteralPath $_ }

function NasCopy($p) {  # the same path inside the NAS archive made by archive_to_nas.ps1
  if ($p -like 'C:\Jasons New Site\www\*') { return Join-Path "$nas\www" $p.Substring('C:\Jasons New Site\www\'.Length) }
  if ($p -like 'D:\*') { return Join-Path "$nas\D" $p.Substring(3) }
}

foreach ($t in $Targets) { $n = NasCopy $t; Write-Output ("seal  $t" + $(if (Test-Path -LiteralPath $n) { "   (+ NAS copy)" } else { '' })) }
if (-not $Apply) { Write-Output "dry run: $($Targets.Count) items. Add -Apply."; return }

New-Item -ItemType Directory -Force $out | Out-Null
$env:PROTON_PASS_KEY_PROVIDER = 'fs'
# 1. password: generated inside Proton Pass, read back into memory only (never printed, never on disk)
$have = pass-cli item view --vault-name 'Keys' --item-title $title --field password 2>$null
if (-not $have) {
  pass-cli item create login --vault-name 'Keys' --title $title --username 'sealed-secrets' --generate-password='48,uppercase'  # format is length + words; '48,true,false' fails "Unknown password option" | Out-Null
  $have = pass-cli item view --vault-name 'Keys' --item-title $title --field password 2>$null
}
$pw = ("$have").Trim()
if ($pw.Length -lt 32) { throw 'could not get the archive password from Proton Pass; nothing was changed' }

# 2. seal (full paths kept inside, names hidden), 3. test
$list = "$env:TEMP\seal-list-$day.txt"
$Targets | Set-Content -LiteralPath $list -Encoding utf8
& $sevenZ a -t7z -mx=5 -mhe=on -spf2 "-p$pw" $arc "@$list" | Out-Null
if ($LASTEXITCODE -ne 0) { throw "7z add failed ($LASTEXITCODE); nothing removed" }
& $sevenZ t "-p$pw" $arc | Out-Null
if ($LASTEXITCODE -ne 0) { throw "7z test failed ($LASTEXITCODE); nothing removed" }
$pw = $null; $have = $null
Remove-Item -LiteralPath $list
"sealed $day : $($Targets.Count) items; archive $([math]::Round((Get-Item $arc).Length/1MB,1)) MB; password = Proton Pass Keys/'$title'" | Set-Content "$out\README-$day.txt"
$Targets | Add-Content "$out\README-$day.txt"
Write-Output "archive OK: $arc"

# 4. second copy on the NAS
if (Test-Path $nas) { New-Item -ItemType Directory -Force "$nas\sealed" | Out-Null; Copy-Item $arc, "$out\README-$day.txt" "$nas\sealed\" -Force; Write-Output 'copied to NAS' }

# 5. remove plain copies (PC/D: and their NAS archive twins): a separate, deliberate step (-Remove),
#    run by Jason after he has opened the archive once with the Pass password and seen it is complete.
if (-not $Remove) { Write-Output "sealed. Plain copies are still in place; check the archive, then run again with -Apply -Remove."; return }
foreach ($t in $Targets) {
  if ($t -like '*\.claude\worktrees') {
    Push-Location 'C:\Jasons New Site\www\ai-stack'
    git worktree list --porcelain | Select-String '^worktree (.+/\.claude/worktrees/.+)$' | ForEach-Object { git worktree remove --force $_.Matches[0].Groups[1].Value 2>&1 | Out-Null }
    git worktree prune
    Pop-Location
  }
  if (Test-Path -LiteralPath $t) { Remove-Item -LiteralPath $t -Recurse -Force }
  $n = NasCopy $t
  if ($n -and (Test-Path -LiteralPath $n)) { Remove-Item -LiteralPath $n -Recurse -Force }
  Write-Output "removed $t"
}
$line = @{ ts = (Get-Date).ToString('s'); job = 'seal_secrets'; ok = $true; detail = "$($Targets.Count) items sealed to $arc" } | ConvertTo-Json -Compress
Add-Content 'D:\joblog\events.jsonl' $line
Write-Output 'PASS seal_secrets'
