def is_code(p: Path) -> bool:
    return p.suffix.lower() in CODE_EXT or p.name in CODE_NAMES or p.name.startswith("Dockerfile")


def describe(rel: str, p: Path) -> str:
    doc = ROOT / "docs" / "code" / (rel + ".md")
    if doc.is_file():
        m = re.search(r"## What it does\s+(.+?)(?:\n\n|\n#)", doc.read_text("utf-8", "replace"), re.DOTALL)
        if m:
            return re.split(r"(?<=[.!?])\s", " ".join(m.group(1).split()), maxsplit=1)[0][:160]
    try:
        for line in p.read_text("utf-8", "replace").splitlines()[:15]:
            t = line.strip().lstrip("#/*;'\"-<!>:@ ").replace("REM ", "").strip()
            if len(t) > 12 and not t.lower().startswith(("!/", "requires", "usr/bin", "echo off", "coding", "set ")):
                return t[:160]
    except OSError:
        pass
    return ""


ARCHIVE_LOG = Path(r"D:\ai-stack-archive\moves-inventory.csv")


def archived_rows() -> list[tuple[str, str, str, str]]:
    """Files already moved to D:\\ai-stack-archive by archive_by_inventory.py, listed under their
    old ai-stack path, so the file keeps describing the codebase as it was before the clean-up."""
    import csv
    out = []
    if not ARCHIVE_LOG.is_file():
        return out
    with open(ARCHIVE_LOG, encoding="utf-8") as fh:
        for src, dst in csv.reader(fh):
            rel0 = os.path.relpath(src, ROOT).replace("\\", "/")
            if rel0.startswith("docs/") or not os.path.exists(dst):
                continue
            status, why = DECISIONS.get(rel0.split("/")[0], ("outdated", "pi-digits backup copy"))
            walk = [(dst, [], [""])] if os.path.isfile(dst) else os.walk(dst)
            for dp, dns, fns in walk:
                dns[:] = [d for d in dns if d not in SKIP_DIRS]
                for f in fns:
                    p = Path(dp, f) if f else Path(dst)
                    rel = rel0 if not f else rel0 + "/" + os.path.relpath(p, dst).replace("\\", "/")
                    if GARDEN.search(rel) or not (is_code(p) or rel in DECISIONS):
                        continue
                    what = describe(rel, p)
                    if GARDEN.search(what):
                        continue
                    out.append((rel, status, why + " (now in {})".format(WHERE_TO.get(status, "D:")), what))
    return out


def main() -> None:
    rows = archived_rows()
    garden = 0
    for dp, dns, fns in os.walk(ROOT):
        rel_dir = os.path.relpath(dp, ROOT).replace("\\", "/")
        dns[:] = sorted(d for d in dns if d not in SKIP_DIRS and not d.startswith("bak-before-") and ";" not in d)
        for f in sorted(fns):
            p = Path(dp, f)
            rel = (f if rel_dir == "." else rel_dir + "/" + f)
            top = rel.split("/")[0]
            if GARDEN.search(rel):
                # Counted, never listed by name: the file names include private material that
                # must never be committed or mentioned (first build on 2026-11-12 listed them).
                garden += 1
                continue
            if not is_code(p) and rel not in DECISIONS:
                continue
            status, why = DECISIONS.get(rel) or DECISIONS.get(top) or ("used", "")
            what = describe(rel, p)
            if GARDEN.search(what) or re.search(r"(?i)\bletters?\b", what):
                garden += 1  # Robin-package tooling (e.g. scratchpad/files/diag*.sh): not listed either
                continue
            rows.append((rel, status, why, what))
    rows.sort()
    counts = {}
    for r in rows:
        counts[r[1]] = counts.get(r[1], 0) + 1
    lines = [
        "# SCRATCHPAD: every code file in ai-stack (built 2026-11-12, before the clean-up)",
        "",
        "What this file is: a reference list of every code file in `ai-stack`, made just before the",
        "2026-11-12 clean-up, so nothing is lost when folders move. Rebuild it any time with",
        "`python -I scripts/build_code_inventory.py` (documented in `docs/code/scripts/build_code_inventory.py.md`).",
        "",
        "Status words:",
        "- **used**: something runs it (compose service or mount, Caddy, a scheduled task, another script, or you start it by hand).",
        "- **outdated**: nothing uses it any more, or it is a stale copy of something that lives elsewhere. Moved to `{}`.".format(WHERE_TO["outdated"]),
        "- **one time use**: a script that did one past job. Moved to `{}`.".format(WHERE_TO["one time use"]),
        "",
        "Counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())),
        "",
        f"Garden for All and Robin's Garden material ({garden} files) is left exactly as it is and is not listed.",
        "",
        "The browsable version with search and share links is the Rust scratchpad page (`/scratchpad`).",
        "",
        "| File | Status | Why | What it does |",
        "|---|---|---|---|",
    ]
    for rel, status, why, what in rows:
        lines.append("| `{}` | {} | {} | {} |".format(rel, status, why.replace("|", "/"), what.replace("|", "/")))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"PASS {OUT.name}: {len(rows)} files ({counts})")


if __name__ == "__main__":
    main()
