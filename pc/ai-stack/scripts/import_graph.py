#!/usr/bin/env python3
"""import_graph.py: which Python file imports which other file in this repo (2026-11-01).

    python scripts/import_graph.py        # writes docs/CONNECTIONS-PYTHON.md

Step 2 of the To Do item "verify the code docs by running the code": a real map built from the code
itself (ast), not from a model's reading. No model, no network, never edits source; it only writes
docs/CONNECTIONS-PYTHON.md. Same file scope as the doc backfill (doc_backfill.eligible).

How an import is matched to a repo file (only repo files are listed; stdlib/pip imports are ignored):
  1. dotted path from the repo root       (import hermes.app.tools -> hermes/app/tools.py)
  2. relative to the importing file's dir (import store            -> <same folder>/store.py)
  3. a package folder with __init__.py    (import pkg              -> pkg/__init__.py)
A name that matches two files is listed under the first rule that matches; a dynamic import
(importlib, __import__) is NOT seen. Treat the map as "at least these", not "only these".
Confirmed 2026-11-01 by spot-checking kb/ (see the run notes in the generated file's header).
"""
import ast
import os
import subprocess
import sys
import warnings

warnings.simplefilter("ignore", SyntaxWarning)   # some scanned files have old-style "\ " escapes; not our problem here

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import doc_backfill  # noqa: E402  (reuse its eligible() scope rules)

OUT = os.path.join(REPO, "docs", "CONNECTIONS-PYTHON.md")


def tracked_python():
    out = subprocess.run(["git", "-C", REPO, "ls-files", "*.py"], capture_output=True, text=True,
                         encoding="utf-8", errors="replace").stdout
    return [l for l in out.splitlines() if doc_backfill.eligible(l)]


def modules_in(source):
    """Dotted module names a file imports (absolute only; `from . import x` handled by the caller)."""
    names = []
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.Import):
            names += [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            if node.level == 0 and node.module:
                names.append(node.module)
                names += [node.module + "." + a.name for a in node.names]   # `from pkg import submodule`
            elif node.level:
                names.append(("." * node.level) + (node.module or ""))
                names += [("." * node.level) + (node.module + "." if node.module else "") + a.name for a in node.names]
    return names


def resolve(name, importer, files):
    folder = os.path.dirname(importer)
    if name.startswith("."):
        base = folder
        for _ in range(len(name) - len(name.lstrip(".")) - 1):
            base = os.path.dirname(base)
        rest = name.lstrip(".").replace(".", "/")
        candidates = [os.path.join(base, rest)]
    else:
        rest = name.replace(".", "/")
        candidates = [rest, os.path.join(folder, rest)]
    for c in candidates:
        c = c.replace("\\", "/").lstrip("/")
        for hit in (c + ".py", c + "/__init__.py"):
            if hit in files and hit != importer:
                return hit
    return None


def main():
    files = set(tracked_python())
    imports = {}
    skipped = []
    for f in sorted(files):
        try:
            source = open(os.path.join(REPO, f), encoding="utf-8", errors="replace").read()
            found = {resolve(n, f, files) for n in modules_in(source)}
        except (SyntaxError, ValueError) as e:
            skipped.append("%s (%s)" % (f, type(e).__name__))
            continue
        imports[f] = sorted(x for x in found if x)
    imported_by = {}
    for f, deps in imports.items():
        for d in deps:
            imported_by.setdefault(d, []).append(f)

    lines = ["# Python connections (generated by scripts/import_graph.py, do not edit by hand)", "",
             "Built from the code with `ast`, not from a model. Only repo files are listed. Dynamic imports "
             "(`importlib`, `__import__`) are not seen, so read this as \"at least these\".", "",
             "%d Python files, %d with an import of another repo file." % (len(files), sum(1 for v in imports.values() if v)), ""]
    if skipped:
        lines += ["Could not parse (left out): " + ", ".join(skipped), ""]
    for f in sorted(imports):
        deps, users = imports[f], sorted(imported_by.get(f, []))
        if not deps and not users:
            continue
        lines.append("## " + f)
        lines.append("- imports: " + (", ".join("`%s`" % d for d in deps) if deps else "none in the repo"))
        lines.append("- imported by: " + (", ".join("`%s`" % u for u in users) if users else "nothing in the repo (entry point, script or unused)"))
        lines.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("PASS %d files, %d connected, wrote %s" % (len(files), sum(1 for f in imports if imports[f] or f in imported_by), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
