"""Register one OIDC client with the household issuer, without printing it.

WHY A SCRIPT AND NOT A HAND EDIT. OIDC_CLIENTS is a single line of JSON in
the PC's .env holding every client in the house -- Immich, Jellyfin,
Paperless, the phone apps. Editing that by hand means opening a file with
nine secrets in it to add a tenth, and one mistyped brace takes every
sign-in in the household down at once. This parses it, adds one entry, and
writes it back.

NOTHING IS EVER PRINTED. The secret is generated here, written straight
into the file, and reported only as its length. Five credentials have
leaked into working transcripts on this project, one of them on the day
this was written, every single time from a command that displayed a value
while answering a question about a name.

THE REDIRECT URI IS MATCHED EXACTLY by the issuer -- never as a pattern --
so it has to be the string the application will actually send. For Wiki.js
that is https://<host>/login/<strategy-uuid>/callback, and the UUID is
generated by Wiki.js when the strategy is created. It cannot be guessed,
which is why this takes it as an argument.

A BACKUP IS TAKEN FIRST, because the failure mode is every OIDC login in
the house at once.

    python register_oidc_client.py wikijs https://wiki.../login/<uuid>/callback
"""
from __future__ import annotations

import base64
import json
import os
import pathlib
import re
import secrets
import shutil
import sys
from datetime import datetime

ENV = pathlib.Path(os.environ.get(
    "AI_STACK_ENV", r"C:\Jasons New Site\www\ai-stack\.env"))
KEY = "OIDC_CLIENTS"


def load_line(text):
    """The OIDC_CLIENTS line, or (None, None). Handles quoted values."""
    for i, line in enumerate(text.splitlines()):
        if line.startswith(KEY + "="):
            raw = line[len(KEY) + 1:].strip()
            if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "'\"":
                raw = raw[1:-1]
            return i, raw
    return None, None


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: register_oidc_client.py <client-id> <redirect-uri> "
                 "[more redirect uris...]")
    client_id = sys.argv[1].strip()
    redirects = [a.strip() for a in sys.argv[2:] if a.strip()]

    if not re.fullmatch(r"[a-z0-9][a-z0-9._-]{2,63}", client_id):
        sys.exit("client id should be lowercase letters, digits, . _ or -")
    for r in redirects:
        if not (r.startswith("https://") or "://" in r):
            sys.exit(f"redirect uri looks wrong: {r}")

    if not ENV.is_file():
        sys.exit(f"no .env at {ENV}")
    text = ENV.read_text(encoding="utf-8")
    idx, raw = load_line(text)
    if idx is None:
        sys.exit(f"{KEY} is not in {ENV}")

    try:
        clients = json.loads(raw) if raw.strip() else []
    except ValueError as e:
        sys.exit(f"{KEY} is not valid JSON ({e}); not touching it")
    if not isinstance(clients, list):
        sys.exit(f"{KEY} is not a list; not touching it")

    if any(c.get("id") == client_id for c in clients):
        sys.exit(f"{client_id} is already registered. Remove it first if you "
                 f"mean to change its redirect uris.")

    # 32 bytes, urlsafe. Long enough that it is never the weak link, short
    # enough to paste into an admin form without wrapping.
    secret = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode().rstrip("=")
    clients.append({"id": client_id, "secret": secret,
                    "redirect_uris": redirects})

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    # 2026-11-12: .env backups live in D:\ai-stack-archive\env-backups (out of the repo folder);
    # beside .env only when D: is missing.
    bak_dir = pathlib.Path(r"D:\ai-stack-archive\env-backups")
    if not pathlib.Path("D:/").exists():
        bak_dir = ENV.parent
    bak_dir.mkdir(parents=True, exist_ok=True)
    backup = bak_dir / (ENV.name + ".bak-" + stamp)
    shutil.copy2(ENV, backup)

    lines = text.splitlines()
    lines[idx] = f"{KEY}={json.dumps(clients, separators=(',', ':'))}"
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"  registered {client_id}")
    print(f"  redirect uris: {len(redirects)}")
    print(f"  secret: {len(secret)} characters, written to {ENV.name} "
          f"-- NOT shown here")
    print(f"  backup: {backup.name}")
    print(f"  {len(clients)} clients now registered")
    print()
    print("  Restart the auth service to load it:")
    print("    docker compose -f docker-compose.yml -f docker-compose.web.yml "
          "up -d auth")


if __name__ == "__main__":
    main()
