<#
.SYNOPSIS
  One-time "finish the setup" job for SuperNova (Jason, 2026-11-04). Runs by itself 15 minutes
  after the next boot (schedule-finish-setup.ps1 registers it), so Windows Update can finish
  first. Every step logs to pc-cleanup\finish-setup.log; read it over SSH:
    type "C:\Jasons New Site\www\pc-cleanup\finish-setup.log"

  Jason's answers (2026-11-04): uninstall the sure list, dev extras, LM Studio (APP ONLY, models
  kept), games + creative extras; Sysmon with the SwiftOnSecurity config; narrow debloat now,
  WinUtil Standard by hand (its unattended mode isn't documented); auto-login via Autologon
  (password typed by Jason, never by a script).

  NEVER TOUCHED: Docker, WSL, Hyper-V, Tailscale, No-IP, OpenSSH, Ollama, llama.cpp, Voicebox,
  windows_exporter, Vector, NVIDIA driver + CUDA, Python 3.11 (it is the default `python` on
  PATH, so removing it would break scripts), any AI model files.

  Each phase is independent: one failing is logged and the next still runs. Nothing is deleted
  that isn't regenerated by Windows (temp files, update cache, old crash dumps, old logs);
  C:\PHP is MOVED to D:\archive, not deleted.
#>
param([switch]$KeepTask)
$ErrorActionPreference = 'Continue'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$log = Join-Path $here 'finish-setup.log'
function Say($m) { $l = "{0}  {1}" -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $m; Add-Content $log $l -Encoding utf8; Write-Host $l }
function Phase($name, [scriptblock]$body) {
  Say "=== $name"
  try { & $body } catch { Say "  FAILED: $($_.Exception.Message)" }
}
Say "finish-setup start (user: $env:USERNAME)"

Phase 'Restore point' {
  Enable-ComputerRestore -Drive 'C:\' -ErrorAction SilentlyContinue
  Checkpoint-Computer -Description 'Before finish-setup 2026-11-04' -RestorePointType MODIFY_SETTINGS -ErrorAction Stop
  Say '  restore point made'
}

Phase 'Quiet 20 background services (backup + undo file in pc-cleanup)' {
  # Jason ran it by hand on 2026-11-04 (backup services-backup-20261104-1432.json). Running it again would
  # write a second backup that records the already-quiet state, so skip when the first one exists.
  if (Get-ChildItem (Join-Path $here 'services-backup-*.json') -ErrorAction SilentlyContinue) { Say '  already done (backup exists); skipped'; return }
  & (Join-Path $here 'quiet-services.ps1') -Apply *>&1 | ForEach-Object { Say "  $_" }
}

Phase 'Windows telemetry, ads and suggestions off (machine policies)' {
  $set = @(
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\DataCollection', 'AllowTelemetry', 1),            # "Required" only (Pro minimum)
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\CloudContent', 'DisableWindowsConsumerFeatures', 1), # no auto-installed promo apps
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\AdvertisingInfo', 'DisabledByGroupPolicy', 1),
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\System', 'EnableActivityFeed', 0),
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\System', 'PublishUserActivities', 0),
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\Windows Search', 'AllowCortana', 0),
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\WindowsCopilot', 'TurnOffWindowsCopilot', 1),
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\AppCompat', 'DisableInventory', 1),
    @('HKLM:\SOFTWARE\Policies\Microsoft\Windows\WindowsUpdate\AU', 'NoAutoRebootWithLoggedOnUsers', 1)  # no surprise reboots
  )
  foreach ($s in $set) {
    New-Item -Path $s[0] -Force | Out-Null
    Set-ItemProperty -Path $s[0] -Name $s[1] -Value $s[2] -Type DWord
    Say "  $($s[0] | Split-Path -Leaf)\$($s[1]) = $($s[2])"
  }
}

Phase 'Uninstall the chosen programs' {
  # DisplayName patterns, matched exactly as written (regex, anchored). Kept tight on purpose.
  $want = @(
    '^TeamViewer', '^Intel. Driver & Support Assistant', '^Intel\(R\) Computing Improvement Program', '^Player Location Check$',
    '^Brother PowerENGAGE$', '^Nightwater Demo$', '^Native Instruments Guitar Rig 5$', '^Native Instruments Kontakt$',
    '^MySQL Workbench$', '^Microsoft Windows Desktop Runtime - 8\.0\.(19|22) ', '^Microsoft \.NET 8\.0\.19 - Windows Server Hosting$',
    '^Microsoft ASP\.NET Core 8\.0\.22 ',
    '^NVIDIA Nsight (Compute|Systems|Visual Studio Edition)', '^Windows Software Development Kit - Windows 10\.0\.22621', '^Oracle VirtualBox',
    '^IIS 10\.0 Express$', '^IIS URL Rewrite Module 2$', '^Microsoft Application Request Routing 3\.0$', '^Python 3\.10\.',
    '^LM Studio', '^Bionic ',
    '^Epic Games Launcher$', '^Epic Online Services$', '^GOG GALAXY$', '^Maxon Cinema 4D', '^IDA Classroom', '^Kofax PaperPort 14$',
    '^Kofax PDF Viewer SE$', '^PaperPort Image Printer', '^Creality Slicer'
  )
  $keys = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*', 'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
  $apps = Get-ItemProperty $keys -ErrorAction SilentlyContinue | Where-Object { $_.DisplayName }
  $manual = @()
  foreach ($a in $apps) {
    if (-not ($want | Where-Object { $a.DisplayName -match $_ })) { continue }
    $guid = if ($a.PSChildName -match '^\{[0-9A-F-]+\}$') { $a.PSChildName } else { $null }
    if ($a.WindowsInstaller -eq 1 -and $guid) {
      $p = Start-Process msiexec.exe -ArgumentList "/x $guid /qn /norestart" -Wait -PassThru
      Say "  msi  $($a.DisplayName): exit $($p.ExitCode)"
    } elseif ($a.QuietUninstallString) {
      $p = Start-Process cmd.exe -ArgumentList "/c `"$($a.QuietUninstallString)`"" -Wait -PassThru
      Say "  exe  $($a.DisplayName): exit $($p.ExitCode)"
    } else { $manual += $a.DisplayName }
  }
  if ($manual) { Say "  REMOVE BY HAND (no silent uninstaller): $($manual -join '; ')" }
  Say '  LM Studio models in C:\Users\USER\.lmstudio were NOT touched (Jason decides later).'
  if (Test-Path 'C:\PHP') {
    New-Item -ItemType Directory -Force 'D:\archive\retired-2026-11-04' | Out-Null
    Move-Item 'C:\PHP' 'D:\archive\retired-2026-11-04\PHP' -Force
    Say '  C:\PHP moved to D:\archive\retired-2026-11-04\PHP'
  }
}

Phase 'Optional Windows features nothing here uses (off; takes effect next reboot)' {
  # Only these, and only if on. Hyper-V, WSL, VirtualMachinePlatform, Containers, Sandbox, .NET stay.
  $off = 'MicrosoftWindowsPowerShellV2Root', 'MicrosoftWindowsPowerShellV2', 'SMB1Protocol', 'WorkFolders-Client',
         'Printing-XPSServices-Features', 'Internet-Explorer-Optional-amd64', 'IIS-WebServerRole', 'IIS-HostableWebCore'
  $on = Get-WindowsOptionalFeature -Online | Where-Object State -eq 'Enabled'
  Say "  enabled now: $(($on.FeatureName | Sort-Object) -join ', ')"
  foreach ($f in $on | Where-Object { $off -contains $_.FeatureName }) {
    Disable-WindowsOptionalFeature -Online -FeatureName $f.FeatureName -NoRestart -ErrorAction Continue | Out-Null
    Say "  turned off: $($f.FeatureName)"
  }
}

Phase 'Sysmon with the SwiftOnSecurity config' {
  $sysmon = 'C:\Jasons New Site\sysadmin\Sysmon64.exe'   # where Jason's Sysinternals suite is (found 2026-11-04)
  if (-not (Test-Path $sysmon)) { $sysmon = (Get-Command sysmon64.exe -ErrorAction SilentlyContinue).Source }
  if (-not $sysmon) {
    $sysmon = Get-ChildItem 'C:\Program Files\WindowsApps', 'C:\Program Files', 'C:\Tools', 'C:\Users\USER' -Filter Sysmon64.exe -Recurse -Depth 5 -ErrorAction SilentlyContinue | Select-Object -First 1 -ExpandProperty FullName
  }
  if (-not $sysmon) { Say '  Sysmon64.exe not found; skipped. Tell Claude where Sysinternals is installed.'; return }
  $cfg = Join-Path $here 'sysmonconfig-export.xml'
  Invoke-WebRequest 'https://raw.githubusercontent.com/SwiftOnSecurity/sysmon-config/master/sysmonconfig-export.xml' -OutFile $cfg -UseBasicParsing
  if ((Get-Item $cfg).Length -lt 10000 -or -not (Select-String -Path $cfg -Pattern '<Sysmon' -Quiet)) { throw 'config download looks wrong' }
  if (Get-Service Sysmon64 -ErrorAction SilentlyContinue) { & $sysmon -c $cfg 2>&1 | Out-Null; Say '  Sysmon config updated' }
  else { & $sysmon -accepteula -i $cfg 2>&1 | Out-Null; Say "  Sysmon installed from $sysmon" }
  wevtutil sl Microsoft-Windows-Sysmon/Operational /ms:268435456   # cap its log at 256 MB
  Say "  Sysmon service: $((Get-Service Sysmon64 -ErrorAction SilentlyContinue).Status)"
}

Phase 'Clean regenerable files (temp, update cache, crash dumps, old logs)' {
  $before = (Get-PSDrive C).Free
  $targets = @("C:\Windows\Temp\*", "C:\Users\USER\AppData\Local\Temp\*", "C:\Windows\SoftwareDistribution\Download\*",
               "C:\ProgramData\Microsoft\Windows\WER\ReportArchive\*", "C:\ProgramData\Microsoft\Windows\WER\ReportQueue\*",
               "C:\Users\USER\AppData\Local\CrashDumps\*")
  foreach ($t in $targets) { Get-ChildItem $t -Force -ErrorAction SilentlyContinue | Where-Object { $_.LastWriteTime -lt (Get-Date).AddDays(-2) } | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue }
  # logs over 90 days old (same window as Loki); C:\Windows\Minidump is KEPT (the 9/15 crash dump is evidence)
  foreach ($d in 'C:\Windows\Logs\CBS', 'C:\Windows\Logs\DISM', 'C:\Windows\Panther', 'C:\ProgramData\Microsoft\Windows\WER\Temp') {
    Get-ChildItem $d -Recurse -File -Force -ErrorAction SilentlyContinue | Where-Object { $_.LastWriteTime -lt (Get-Date).AddDays(-90) } | Remove-Item -Force -ErrorAction SilentlyContinue
  }
  # Event logs: only report big ones; clearing them would erase history Jason may want
  Get-WinEvent -ListLog * -ErrorAction SilentlyContinue | Where-Object { $_.FileSize -gt 100MB } |
    ForEach-Object { Say ("  big event log (kept): {0} {1:N0} MB" -f $_.LogName, ($_.FileSize / 1MB)) }
  Dism.exe /Online /Cleanup-Image /StartComponentCleanup /Quiet | Out-Null   # superseded update files
  Say ("  freed about {0:N1} GB" -f (((Get-PSDrive C).Free - $before) / 1GB))
}

Phase 'Lock the screen right after an automatic sign-in (for Autologon)' {
  $a = New-ScheduledTaskAction -Execute 'rundll32.exe' -Argument 'user32.dll,LockWorkStation'
  $t = New-ScheduledTaskTrigger -AtLogOn -User 'SUPERNOVA\USER'; $t.Delay = 'PT45S'
  $p = New-ScheduledTaskPrincipal -UserId 'SUPERNOVA\USER' -LogonType Interactive
  Register-ScheduledTask -TaskName 'Lock after auto sign-in' -Action $a -Trigger $t -Principal $p -Force | Out-Null
  Say '  task "Lock after auto sign-in" registered (locks 45 s after you sign in; Docker keeps starting)'
}

Phase 'The fix command (Docker Fix task + fix.cmd)' {
  if (Get-ScheduledTask -TaskName 'Docker Fix' -ErrorAction SilentlyContinue) { Say '  already installed; skipped'; return }
  & (Join-Path (Split-Path $here) 'ai-stack\install-fix.ps1') -User 'SUPERNOVA\USER' -HomeDir 'C:\Users\USER' *>&1 | ForEach-Object { Say "  $_" }
}

if (-not $KeepTask) { Unregister-ScheduledTask -TaskName 'Finish setup (one time)' -Confirm:$false -ErrorAction SilentlyContinue; Say 'one-time task removed' }
Say 'finish-setup DONE. Still yours: Autologon (type your password in its window), WinUtil Standard, the cleanup review list. Reboot once more so the feature changes apply.'
