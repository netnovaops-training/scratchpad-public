#!/usr/bin/env python3
"""make_drop_config.py - write the first drop.toml from the people tables now in the intake code (T0927 slice 1).

    python3 make_drop_config.py SRC_DIR OUT_FILE      e.g. ~/nuc-homelab/intake ~/.config/drop/drop.toml

Reads portal.py (WHO, PRIVATE_OK, NAMES) and classify.py (PEOPLE, SHELF) with ast.literal_eval: the code is
parsed, never run. Writes OUT_FILE with mode 600 and refuses to overwrite an existing one. Prints counts only,
never an email address. Run once; after that, people are edited in drop.toml, not in the code.

Variables: TABLES (the five assignment names read), src/out (arguments).
"""
import ast
import os
import sys
from pathlib import Path

TABLES = {"portal.py": ("WHO", "PRIVATE_OK", "NAMES"), "classify.py": ("PEOPLE", "SHELF")}


def tables(src: Path) -> dict:
    """The five old tables, read as Python literals from the source files."""
    out = {}
    for fname, names in TABLES.items():
        for node in ast.parse((src / fname).read_text(encoding="utf-8")).body:
            if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], "id", "") in names:
                out[node.targets[0].id] = ast.literal_eval(node.value)
    missing = {n for ns in TABLES.values() for n in ns} - set(out)
    if missing:
        raise SystemExit(f"not found in the code: {sorted(missing)}")
    return out


def q(s: str) -> str:
    """A TOML basic string."""
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(src: Path, dst: Path) -> int:
    if dst.exists():
        raise SystemExit(f"{dst} exists; not overwriting")
    t = tables(src)
    ids = sorted(set(t["WHO"].values()) | set(t["NAMES"]) | set(t["PEOPLE"].values()) | set(t["SHELF"]))
    private_lc = {e.lower() for e in t["PRIVATE_OK"]}
    lines = ["# drop.toml - Atomic Drop settings (T0927). Edit people HERE, not in the code. Mode 600, outside git.",
             "# Format: see dropconfig.py. Generated by make_drop_config.py from the old code tables.", "",
             "[brand]", 'name = "Atomic Share"', 'short_name = "Atomic Share"', 'theme = "atomic"', ""]
    for pid in ids:
        emails = sorted(e.lower() for e, who in t["WHO"].items() if who == pid)
        priv = [e for e in emails if e in private_lc]
        lines += ["[[person]]", f"id = {q(pid)}"]
        if pid in t["NAMES"]:
            lines.append(f"name = {q(t['NAMES'][pid])}")
        lines.append("emails = [" + ", ".join(q(e) for e in emails) + "]")
        lines.append("aliases = [" + ", ".join(q(a) for a, who in t["PEOPLE"].items() if who == pid) + "]")
        if priv:
            lines.append("private = true" if priv == emails else "private = [" + ", ".join(q(e) for e in priv) + "]")
        if pid in t["SHELF"]:
            lines += ["[person.shelves]"] + [f"{k} = {q(v)}" for k, v in t["SHELF"][pid].items()]
        lines.append("")
    stray = private_lc - {e.lower() for e in t["WHO"]}
    if stray:
        raise SystemExit(f"{len(stray)} private address(es) belong to no person; fix the code tables first")
    dst.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd = os.open(dst, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {dst}: {len(ids)} people, {len(t['WHO'])} emails, {len(private_lc)} private, "
          f"{len(t['PEOPLE'])} aliases, {len(t['SHELF'])} shelves (mode 600)")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: make_drop_config.py SRC_DIR OUT_FILE")
    sys.exit(main(Path(sys.argv[1]).expanduser(), Path(sys.argv[2]).expanduser()))
